# N-03 개인정보 비식별화: 통화 텍스트에서 이름/전화번호/계좌번호/주민등록번호로 보이는
# 부분을 정규식 기반으로 마스킹한다. domain 계층 — re는 stdlib이라 프레임워크/외부
# 의존성 없음(entities.py가 이미 collections/dataclasses/datetime/enum 같은 stdlib을
# 쓰는 것과 같은 기준).
#
# WHY 정규식인가 (F-01/F-02가 규칙→LLM으로 갔던 것과 대비): 여기는 반대로 "정확한
# 위치를 안전 마진 넉넉하게 지우는 것"이 목표라 규칙 기반이 더 적합하다. LLM에 맡기면
# "지웠는지 안 지웠는지"를 매 호출 확률적으로 신뢰해야 하는데, PII 마스킹은 결정론적으로
# 항상 같은 패턴을 지워야 하는 게 오히려 요구사항에 더 가깝다.
#
# WHY 마스킹을 mcp-server 호출 "전"에 적용하는가: 전화번호/계좌번호/이름의 구체적인 값은
# 보이스피싱 판정(F-01/F-02)에 필요 없다 — 판정은 "검찰청 사칭", "안전계좌로 이체" 같은
# 문구/패턴에 반응하지, 실제 숫자값에 반응하지 않는다(mcp-server/src/domain/
# pattern_rules.py의 PATTERN_RULES 참고 — PERSONAL_INFO_REQUEST 카테고리도 "계좌번호와
# 비밀번호"라는 요구 문구에 반응하지 실제 계좌번호 자릿수엔 반응하지 않는다). 그래서
# mcp-server(LLM 포함)에 보내는 텍스트 자체를 마스킹된 버전으로 바꿔도 판정 품질에
# 영향이 없고, PII가 외부 프로세스(로컬이라도 Ollama)로 나가는 걸 원천 차단한다.
#
# ⚠️ v1 한계 (정확도 검증 안 됨, 특히 이름 마스킹):
#   - 전화번호/주민등록번호: 형식이 고정돼 있어 정규식 정밀도가 높다.
#   - 계좌번호: 은행마다 자릿수/구분 형식이 달라 "10~16자리 숫자(구분기호 허용)"라는
#     느슨한 휴리스틱을 쓴다 — 전화번호/주민번호로 먼저 마스킹한 나머지 텍스트에서만
#     찾으므로 이중 마스킹은 안 되지만, 계좌번호가 아닌 다른 긴 숫자(예: 사건번호)를
#     오탐할 수 있다.
#   - 이름: 일반적인 한국어 성씨 뒤에 호칭(님/씨)이 붙는 패턴만 잡는다. 성씨 목록 밖의
#     성이거나 호칭 없이 이름만 나오면 놓친다(재현율 낮음, 오탐은 적음). 신뢰도가
#     검증된 개체명 인식(NER) 모델이 아니다 — deepvoice_adapter.py v1과 같은 성격의
#     한계.

import re

_RESIDENT_REGISTRATION_NUMBER = re.compile(r"\d{6}[-\s]?\d{7}")

_PHONE_NUMBER = re.compile(
    r"01[016789][-\s]?\d{3,4}[-\s]?\d{4}"  # 휴대폰: 010-1234-5678 등
    r"|0(?:2|[3-6]\d)[-\s]?\d{3,4}[-\s]?\d{4}"  # 유선: 02-123-4567, 031-123-4567 등
)

# 전화번호/주민번호를 먼저 지운 "나머지" 텍스트에서만 적용 — 10~16자리 숫자(공백/하이픈
# 구분 허용). 계좌번호는 은행마다 형식이 달라 이 이상 정밀하게 잡기 어렵다(위 한계 참고).
_ACCOUNT_NUMBER = re.compile(r"\d[\d\-\s]{8,20}\d")  # 순수 숫자만이면 최소 10자리

# 흔한 한국 성씨 뒤에 이름 1~2음절 + 호칭(님/씨)이 붙는 패턴만 잡는다(재현율 낮은 v1).
_COMMON_SURNAMES = (
    "김|이|박|최|정|강|조|윤|장|임|한|오|서|신|권|황|안|송|류|전|홍|고|문|양|손|배|백|허|유|남|심|노|하|곽|성|차|주"
)
_NAME_WITH_HONORIFIC = re.compile(rf"(?:{_COMMON_SURNAMES})[가-힣]{{1,2}}\s?(?:님|씨)")


def mask_pii(text: str) -> str:
    """전화번호/주민등록번호/계좌번호/이름(호칭 동반)으로 보이는 부분을 대괄호 태그로
    치환한다. 원문 길이/문장 구조는 최대한 보존해 판정 근거(N-04)를 읽을 때 맥락이
    깨지지 않게 한다."""
    masked = _RESIDENT_REGISTRATION_NUMBER.sub("[주민등록번호]", text)
    masked = _PHONE_NUMBER.sub("[전화번호]", masked)
    masked = _ACCOUNT_NUMBER.sub("[계좌번호]", masked)
    masked = _NAME_WITH_HONORIFIC.sub("[이름]", masked)
    return masked
